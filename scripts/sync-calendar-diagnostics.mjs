/**
 * Sync Calendar — Diagnostics report builder (pure).
 *
 * `buildCalendarDiagnostics(input)` takes an already-collected, plain snapshot
 * of the Sync Calendar's state and returns a Markdown report string designed to
 * be copied to the clipboard and pasted into an AI tool (e.g. Claude) or a bug
 * report. It surfaces exactly the things that are otherwise invisible from
 * outside the operator's Foundry world: Calendaria/module versions, the active
 * calendar's structure, the live validation findings (errors/warnings/info),
 * the selected day's notes/moons/season/weather, the API methods Calendaria
 * actually exposes, recent sync errors, and the relevant sync settings.
 *
 * Kept PURE (no Foundry globals, never throws) so it unit-tests cleanly and so
 * the collection side — which must touch `CALENDARIA.api` + Foundry — stays a
 * thin, defensive adapter in `sync-calendar.mjs`.
 */

/** Severity ordering for grouping findings in the report. */
const SEVERITY_ORDER = ['error', 'warning', 'info'];

/**
 * Coerce anything to a short, single-line display string.
 * @param {*} v
 * @returns {string}
 */
function oneLine(v) {
  if (v == null) return '';
  if (typeof v === 'string') return v.replace(/\s+/g, ' ').trim();
  try { return JSON.stringify(v); } catch { return String(v); }
}

/**
 * Pretty-print a value as a fenced JSON block, guarding against cycles.
 * @param {*} v
 * @returns {string}
 */
function jsonBlock(v) {
  let body;
  try { body = JSON.stringify(v, null, 2); } catch { body = String(v); }
  if (body === undefined) body = 'undefined';
  return '```json\n' + body + '\n```';
}

/**
 * Render a `key: value` line, skipping empty values unless `keepEmpty`.
 * @param {string} key
 * @param {*} value
 * @param {boolean} [keepEmpty]
 * @returns {string|null}
 */
function kv(key, value, keepEmpty = true) {
  const s = oneLine(value);
  if (!s && !keepEmpty) return null;
  return `- **${key}:** ${s || '—'}`;
}

/**
 * Build the diagnostics report.
 *
 * Every field is optional; missing data degrades to "—"/"(unknown)" rather than
 * throwing, because the collector gathers each piece under its own try/catch.
 *
 * @param {object} [input]
 * @param {string} [input.generatedAt] - ISO timestamp.
 * @param {object} [input.versions] - { module, calendaria, schema, foundry, system, systemId }.
 * @param {object} [input.calendar] - { name, id, version }.
 * @param {object} [input.syncStatus] - { calendarSyncEnabled, syncEnabled, calendarModule, thisCalendarExcluded }.
 * @param {object} [input.structureCounts] - months, weekdays, seasons, moons, eras, festivals, cycles, weatherZones.
 * @param {object} [input.apiMethods] - map of method name → boolean (present on CALENDARIA.api).
 * @param {object} [input.currentDateTime]
 * @param {object} [input.selectedDate]
 * @param {object} [input.dayDetail] - { notes, moonPhases, season, weatherCurrent, weatherForDate }.
 * @param {Array}  [input.findings] - [{ severity, code, message, fixHint }].
 * @param {Array}  [input.recentErrors] - [{ time, message, endpoint, status }].
 * @param {object} [input.settings] - relevant sync settings snapshot.
 * @param {object} [input.raw] - misc raw objects to append verbatim (weather, note sample, etc.).
 * @returns {string} Markdown report.
 */
export function buildCalendarDiagnostics(input = {}) {
  const i = input || {};
  const L = [];

  L.push('# Chronicle Sync — Calendar Diagnostics');
  L.push('');
  L.push('_Paste this whole block into Claude / a bug report. Generated by the Sync Calendar editor._');
  L.push('');
  L.push(kv('Generated', i.generatedAt || '(unknown)'));
  L.push('');

  // --- Environment / versions ---
  const v = i.versions || {};
  L.push('## Environment');
  L.push(kv('Module', v.module));
  L.push(kv('Calendaria', v.calendaria));
  L.push(kv('Schema', v.schema));
  L.push(kv('Foundry', v.foundry));
  L.push(kv('Game system', v.systemId ? `${v.system || ''} (${v.systemId})` : v.system));
  L.push('');

  // --- Sync status (the on/off question) ---
  const s = i.syncStatus || {};
  L.push('## Sync status');
  L.push(kv('Calendar module detected', s.calendarModule || 'none'));
  L.push(kv('Calendar sync enabled (global)', boolLabel(s.calendarSyncEnabled)));
  L.push(kv('Master sync enabled', boolLabel(s.syncEnabled)));
  L.push(kv('This calendar excluded from sync', boolLabel(s.thisCalendarExcluded)));
  L.push(kv('Calendar sync paused (structure mismatch)', boolLabel(s.calendarSyncPaused)));
  if (s.mismatchDetail) L.push(kv('Mismatch detail', s.mismatchDetail));
  L.push('');

  // --- Calendar identity + structure ---
  const cal = i.calendar || {};
  const sc = i.structureCounts || {};
  L.push('## Active calendar');
  L.push(kv('Name', cal.name));
  L.push(kv('Id', cal.id));
  L.push(kv('Version', cal.version, false) || '');
  L.push('');
  L.push('### Structure counts');
  L.push(kv('Months', sc.months));
  L.push(kv('Weekdays', sc.weekdays));
  L.push(kv('Seasons', sc.seasons));
  L.push(kv('Moons', sc.moons));
  L.push(kv('Eras', sc.eras));
  L.push(kv('Festivals', sc.festivals));
  L.push(kv('Cycles', sc.cycles));
  L.push(kv('Weather zones (custom climate zones)', sc.weatherZones));
  L.push('  > Note: "weather zones" counts custom climate regions only; per-day weather (e.g. a "Meteor Shower" preset) lives in the default zone and is not a zone.');
  L.push('');

  // --- API capability probe ---
  if (i.apiMethods && typeof i.apiMethods === 'object') {
    L.push('## CALENDARIA.api methods available');
    const present = Object.keys(i.apiMethods).filter((k) => i.apiMethods[k]);
    const missing = Object.keys(i.apiMethods).filter((k) => !i.apiMethods[k]);
    L.push(kv('Present', present.join(', ') || 'none'));
    L.push(kv('Missing', missing.join(', ') || 'none'));
    L.push('');
  }

  // --- Selected day detail ---
  const dd = i.dayDetail || {};
  L.push('## Selected day');
  L.push(kv('Date', i.selectedDate ? `${i.selectedDate.day}/${i.selectedDate.month}/${i.selectedDate.year}` : '—'));
  L.push(kv('Current world date/time', i.currentDateTime));
  L.push(kv('Season', dd.season ? (dd.season.name || oneLine(dd.season)) : '—'));
  L.push(kv('Notes on day', Array.isArray(dd.notes) ? `${dd.notes.length}${dd.notes.length ? ' — ' + dd.notes.map((n) => n.name).filter(Boolean).join(', ') : ''}` : '—'));
  L.push(kv('Moon phases', Array.isArray(dd.moonPhases) ? dd.moonPhases.map((m) => `${m.moonName}: ${m.phaseName}`).join('; ') || '—' : '—'));
  L.push(kv('Weather (current date)', dd.weatherCurrent ? (dd.weatherCurrent.label || oneLine(dd.weatherCurrent)) : '—'));
  L.push(kv('Weather (selected date)', dd.weatherForDate ? (dd.weatherForDate.label || oneLine(dd.weatherForDate)) : '—'));
  L.push('');

  // --- Validation findings (the "bottom-left errors") ---
  const findings = Array.isArray(i.findings) ? i.findings : [];
  L.push(`## Validation findings (${findings.length})`);
  if (findings.length === 0) {
    L.push('_No findings._');
  } else {
    for (const sev of SEVERITY_ORDER) {
      const group = findings.filter((f) => f.severity === sev);
      if (!group.length) continue;
      L.push(`### ${sev.toUpperCase()} (${group.length})`);
      for (const f of group) {
        L.push(`- \`${f.code || '?'}\` — ${oneLine(f.message)}${f.fixHint ? ` _(fix: ${oneLine(f.fixHint)})_` : ''}`);
      }
    }
  }
  L.push('');

  // --- Recent sync errors ---
  const errs = Array.isArray(i.recentErrors) ? i.recentErrors : [];
  L.push(`## Recent sync errors (${errs.length})`);
  if (errs.length === 0) {
    L.push('_None recorded._');
  } else {
    for (const e of errs.slice(0, 25)) {
      const meta = [e.endpoint, e.status].filter(Boolean).join(' ');
      L.push(`- ${e.time ? `[${oneLine(e.time)}] ` : ''}${oneLine(e.message)}${meta ? ` (${meta})` : ''}`);
    }
  }
  L.push('');

  // --- Settings snapshot ---
  if (i.settings && typeof i.settings === 'object') {
    L.push('## Sync settings');
    for (const [k, val] of Object.entries(i.settings)) {
      L.push(kv(k, typeof val === 'boolean' ? boolLabel(val) : val));
    }
    L.push('');
  }

  // --- Raw appendix (exact object shapes for debugging) ---
  if (i.raw && typeof i.raw === 'object' && Object.keys(i.raw).length) {
    L.push('## Raw (verbatim object shapes)');
    L.push(jsonBlock(i.raw));
    L.push('');
  }

  return L.filter((line) => line !== null).join('\n');
}

/**
 * Human label for a tri-state boolean (true/false/unknown).
 * @param {*} b
 * @returns {string}
 */
function boolLabel(b) {
  if (b === true) return 'yes';
  if (b === false) return 'no';
  return '(unknown)';
}
